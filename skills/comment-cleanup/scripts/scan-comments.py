def discover(paths, root):
    files, seen = [], set()

    def want(p):
        base = os.path.basename(p)
        if SKIP_FILE_RE.search(base):
            return False
        ext = os.path.splitext(p)[1].lower()
        return ext in EXT_PROFILE or base in NAME_PROFILE

    for p in paths:
        if os.path.isfile(p):
            if want(p) and p not in seen:
                seen.add(p)
                files.append(p)
            continue
        listed = None
        try:
            out = subprocess.run(["git", "-C", p, "ls-files", "-z"], capture_output=True,
                                 text=True, timeout=60)
            if out.returncode == 0:
                listed = [os.path.join(p, f) for f in out.stdout.split("\0") if f]
        except (OSError, subprocess.SubprocessError):
            listed = None
        if listed is None:
            listed = []
            for dirpath, dirnames, filenames in os.walk(p):
                dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS
                               and not d.startswith(".")]
                listed += [os.path.join(dirpath, f) for f in filenames]
        for f in listed:
            rel = os.path.relpath(f, root)
            if any(part in SKIP_DIRS for part in rel.split(os.sep)):
                continue
            if want(f) and f not in seen:
                seen.add(f)
                files.append(f)
    return sorted(files)


def scan_file(path, cap, rules):
    try:
        if os.path.getsize(path) > MAX_FILE_BYTES:
            return None, "too large"
        with open(path, "r", encoding="utf-8", errors="strict") as fh:
            text = fh.read()
    except (OSError, UnicodeDecodeError):
        return None, "unreadable"
    head = "\n".join(text.split("\n", 40)[:40])
    if GENERATED_FILE_RE.search(head):
        return None, "generated"
    if any(len(ln) > 500 for ln in text.split("\n")[:50]):
        return None, "minified"
    units = build_units(path, text)
    if units is None:
        return None, "unsupported"
    findings = []
    for u in units:
        findings += [f for f in check_unit(u, cap) if f["rule"] in rules]
    findings.sort(key=lambda f: (f["line"], f["rule"]))
    return {"comments": len(units), "findings": findings}, None


