#!/usr/bin/env python3
"""Inventory a codebase's comments and flag cleanup candidates.

A repo-wide comment sweep is not tractable by reading every file: the context window runs
out long before the edits start. This script does the mechanical pass first — find every
comment, match it against the antipattern catalogue, and emit a work list the agent can act
on file by file.

Every finding is a *candidate*, not a verdict. The heuristics here cannot read intent, so the
agent must open the file and decide. Rule IDs match references/ANTIPATTERNS.md.

Usage:
    scan-comments.py [paths...] [--json] [--cap N] [--rules ID,ID] [--summary-only]
    scan-comments.py --self-test

Exits 0 for any scan result, including findings — this reports, it never gates.
--self-test exits non-zero on failure so it can be wired into a test suite.
"""

