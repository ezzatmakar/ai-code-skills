def _words(s):
    out = []
    for part in re.findall(r"[A-Za-z][A-Za-z0-9]*", s):
        out.extend(re.findall(r"[A-Z]+(?![a-z])|[A-Z][a-z0-9]*|[a-z0-9]+", part))
    res = []
    for w in out:
        w = w.lower()
        if len(w) <= 2 or w in STOPWORDS:
            continue
        res.append(w[:-1] if w.endswith("s") and len(w) > 3 else w)
    return res


def _assignment(line):
    """True for a real assignment, false for prose shaped like one.

    `# $1 = added+removed line count` documents a shell parameter and `null = absent`
    documents a return value; neither is commented-out code.
    """
    m = ASSIGN_RE.match(line)
    if not m:
        return False
    lhs, rhs = m.group(1), m.group(2).strip()
    if POSITIONAL_RE.match(lhs) or not rhs:
        return False
    return bool(re.search(r"[(){}\[\];\"'`]", rhs) or " " not in rhs)


def _code_like(line):
    return sum(1 for r in CODE_SIGNALS if r.search(line)) + (1 if _assignment(line) else 0)


def _tags(unit):
    found = []
    for ln in unit.lines:
        m = TAG_LINE_RE.match(ln)
        if m:
            found.append((m.group(1).lower(), ln))
    return found


def check_unit(unit, cap):
    findings = []

    def add(rule, line, excerpt, why, disposition=None):
        findings.append({
            "rule": rule, "line": line, "end_line": unit.end,
            "disposition": disposition or DISPOSITION[rule],
            "excerpt": excerpt[:160], "why": why,
        })

    # SECRET first: it applies even to protected units, and it never echoes the value.
    for label, pat in SECRET_PATTERNS:
        for idx, ln in enumerate(unit.lines):
            if pat.search(ln) and not SECRET_FALSE_POSITIVE_RE.search(ln):
                add("SECRET", unit.start + idx, "<redacted>",
                    "possible %s in a comment; verify and rotate, do not just delete" % label)
                break
    if unit.protected:
        return findings

    body = unit.text
    if not body and unit.is_doc:
        add("EMPTY", unit.start, unit.raw.strip().split("\n")[0], "docblock has no content")
        return findings
    if not body:
        return findings

    for idx, ln in enumerate(unit.lines):
        if not ln:
            continue
        if TODO_RE.search(ln) and not TODO_OK_RE.search(ln):
            add("TODO", unit.start + idx, ln, "no tracked issue reference; do not invent one")
            break

    for idx, ln in enumerate(unit.lines):
        if GENERATED_RE.search(ln) or AI_MARK_RE.search(ln) or FILLER_RE.match(ln):
            add("GENERATED", unit.start + idx, ln, "artifact of generation, not of the program")
            break

    banner = False
    if unit.height <= 6:
        for idx, ln in enumerate(unit.lines):
            raw_ln = unit.raw.split("\n")[idx].strip() if idx < unit.height else ""
            pure = (ln and BANNER_RE.match(ln)) or SLASH_BANNER_RE.match(raw_ln)
            labelled = ln and BANNER_TEXT_RE.match(ln)
            if pure:
                add("BANNER", unit.start + idx, raw_ln or ln, "carries no information")
            elif labelled:
                # The label is information; only the divider runs around it are art.
                add("BANNER", unit.start + idx, ln,
                    "strip the divider runs and keep the label, or delete if the label "
                    "only restates the code below", "SHORTEN")
            if pure or labelled:
                banner = True
                break

    for idx, ln in enumerate(unit.lines):
        if not ln or CHANGELOG_EXEMPT_RE.search(ln):
            continue
        if CHANGELOG_RE.search(ln) or VERSION_LOG_RE.match(ln) or DATE_RE.search(ln):
            add("CHANGELOG", unit.start + idx, ln,
                "git records this; keep only an issue link, if any")
            break

    # A docblock is documentation and a trailing note annotates live code — neither is ever
    # a commented-out block, and treating them as one misreads prose that contains parens.
    if not DEAD_EXEMPT_RE.search(body) and not unit.is_doc and not unit.trailing:
        hits = [(i, ln) for i, ln in enumerate(unit.lines)
                if ln and not LIST_ITEM_RE.match(ln) and _code_like(ln)]
        strong = [x for x in hits if re.search(r"[;{}]\s*$", x[1]) or _assignment(x[1])]
        if len(hits) >= 2 or (len(hits) == 1 and strong):
            add("DEAD", unit.start + hits[0][0], hits[0][1], "git already stores this")

    tags = _tags(unit)
    if tags:
        ranks = [(TAG_RANK[t], t) for t, _ in tags if t in TAG_RANK]
        for a, b in zip(ranks, ranks[1:]):
            if b[0] < a[0]:
                add("ORD", unit.start, "@%s before @%s" % (a[1], b[1]),
                    "canonical order is summary, @param, @return, @throws, @deprecated, @see")
                break
        first_tag = next(i for i, ln in enumerate(unit.lines) if TAG_LINE_RE.match(ln))
        if any(unit.lines[i] and not TAG_LINE_RE.match(unit.lines[i])
               and not unit.lines[i].startswith(("-", "*", "|", "```", "  "))
               for i in range(first_tag + 1, len(unit.lines))):
            add("ORD", unit.start + first_tag, unit.lines[first_tag],
                "prose stranded after the first block tag")
        if unit.is_doc and all(BARE_TAG_RE.match(ln) for ln in unit.lines if ln):
            add("EMPTY", unit.start, tags[0][1], "tags add nothing beyond the signature")

    # A file header states the file's purpose. It is expected to be long and to sit a blank
    # line above the first declaration, so the length and placement rules do not apply.
    # Banner art is already reported as BANNER; its placement is not a second finding.
    if not unit.file_header and not banner:
        if unit.trailing and (unit.height > 1 or len(body) > LONG_TRAILING_CHARS):
            add("POS", unit.start, body, "explanation trailing a line of code; move it above")
        elif (not unit.trailing and unit.blank_before_code >= 1 and unit.next_code
                and DECL_RE.match(unit.next_code[1])):
            add("POS", unit.start, body,
                "blank line detaches this from its declaration; doc tools drop it")

        if not unit.is_doc and not unit.trailing and unit.height > cap:
            add("LEN", unit.start, body,
                "%d lines; cap is %d — compress to the load-bearing sentence or move it into "
                "the docblock" % (unit.height, cap))

    # The subject of a trailing comment is the code it sits on, not the next line.
    subject = unit.own_code if unit.trailing else (
        unit.next_code[1] if unit.next_code and unit.blank_before_code == 0 else "")
    # A comment attached to a declaration is documentation, and naming the symbol is the
    # convention — `// Copy copies from src to dst.` is required Go doc form, not a duplicate.
    documents_decl = not unit.trailing and subject and DECL_RE.match(subject)
    if (unit.height == 1 and not unit.is_doc and subject and not documents_decl
            and not ENUM_RE.search(body)):
        cw = _words(body)
        if cw and len(cw) <= 6:
            code_w = set(_words(subject))
            shared = [w for w in cw if w in code_w]
            ratio = len(shared) / len(cw)
            if shared and (ratio >= 0.5 or (cw[0] in NARRATION_VERBS and ratio >= 0.3)):
                add("DUP", unit.start, body, "restates `%s`" % subject.strip()[:60])
    return findings


