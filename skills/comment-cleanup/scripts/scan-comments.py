def _line_index(text):
    starts = [0]
    for m in re.finditer("\n", text):
        starts.append(m.end())
    return starts


def _pos(starts, off):
    ln = bisect_right(starts, off)
    return ln, off - starts[ln - 1]


def _regex_allowed(text, i):
    """True when a `/` at offset i starts a JS regex literal rather than division."""
    j = i - 1
    while j >= 0 and text[j] in " \t\r\n":
        j -= 1
    if j < 0:
        return True
    if text[j] in "=(,:[!&|?{};+-*%~^<>":
        return True
    k = j
    while k >= 0 and (text[k].isalnum() or text[k] == "_"):
        k -= 1
    return text[k + 1:j + 1] in {
        "return", "typeof", "instanceof", "in", "of", "new", "delete", "void", "throw",
        "case", "do", "else", "yield", "await",
    }


def _skip_string(text, i, prof):
    """If a string literal starts at i, return the offset just past it, else None."""
    n = len(text)
    for opener, closer, escapes in prof.strings:
        if text.startswith(opener, i):
            j = i + len(opener)
            while j < n:
                c = text[j]
                if escapes and c == "\\":
                    j += 2
                    continue
                if c == "\n" and opener in ("'", '"'):
                    return j          # unterminated line string; resync at the newline
                if text.startswith(closer, j):
                    return j + len(closer)
                j += 1
            return n
    if prof.template and text[i] == "`":
        j, depth = i + 1, 0
        while j < n:
            c = text[j]
            if c == "\\":
                j += 2
                continue
            if text.startswith("${", j):
                depth += 1
                j += 2
                continue
            if c == "}" and depth:
                depth -= 1
            elif c == "`" and not depth:
                return j + 1
            j += 1
        return n
    return None


def _skip_regex(text, i):
    n, j, in_class = len(text), i + 1, False
    while j < n:
        c = text[j]
        if c == "\\":
            j += 2
            continue
        if c == "\n":
            return None
        if c == "[":
            in_class = True
        elif c == "]":
            in_class = False
        elif c == "/" and not in_class:
            j += 1
            while j < n and text[j].isalpha():
                j += 1
            return j
        j += 1
    return None


def extract_generic(text, prof):
    """Comment spans as (start_off, end_off, kind), string- and regex-aware."""
    spans, n, i = [], len(text), 0
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
            continue
        s = _skip_string(text, i, prof)
        if s is not None:
            i = s
            continue
        hit = None
        for opener, closer in prof.block:
            if text.startswith(opener, i):
                end = text.find(closer, i + len(opener))
                end = n if end == -1 else end + len(closer)
                hit = (i, end, "block")
                break
        if hit:
            spans.append(hit)
            i = hit[1]
            continue
        for marker in prof.line:
            if text.startswith(marker, i):
                end = text.find("\n", i)
                end = n if end == -1 else end
                hit = (i, end, "line")
                break
        if hit:
            spans.append(hit)
            i = hit[1]
            continue
        if prof.regex and c == "/" and _regex_allowed(text, i):
            r = _skip_regex(text, i)
            if r:
                i = r
                continue
        i += 1
    return spans


def extract_python(text):
    """Python comments and docstrings via tokenize, which never misreads a string."""
    out = []
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError, ValueError):
        return None
    at_stmt_start = True
    for tok in toks:
        if tok.type == tokenize.COMMENT:
            out.append((tok.start, tok.end, "line", tok.string))
        elif tok.type == tokenize.STRING:
            if at_stmt_start and tok.string.lstrip("rRbBuUfF")[:3] in ('"""', "'''"):
                out.append((tok.start, tok.end, "docstring", tok.string))
            at_stmt_start = False
        elif tok.type in (tokenize.NEWLINE, tokenize.NL, tokenize.INDENT,
                          tokenize.DEDENT, tokenize.ENCODING):
            at_stmt_start = True
        elif tok.type != tokenize.COMMENT:
            at_stmt_start = False
    return out


# ---------------------------------------------------------------------------
# Units — a comment plus the context needed to judge it
# ---------------------------------------------------------------------------


class Unit:
    def __init__(self, start, end, kind, raw, lines, indent, trailing):
        self.start = start          # 1-based first line
        self.end = end              # 1-based last line
        self.kind = kind            # line | block | docstring
        self.raw = raw
        self.lines = lines          # marker-stripped content, one entry per source line
        self.indent = indent
        self.trailing = trailing    # code precedes the comment on its first line
        self.own_code = ""          # that preceding code — the subject of a trailing comment
        self.next_code = None       # (lineno, text) of the next real code line
        self.blank_before_code = 0
        self.protected = False
        self.file_header = False    # states the file's purpose; length and gap are expected

    @property
    def height(self):
        return self.end - self.start + 1

    @property
    def text(self):
        return " ".join(x for x in self.lines if x).strip()

    @property
    def is_doc(self):
        r = self.raw.lstrip()
        return (self.kind == "docstring" or r.startswith("/**") or r.startswith("///")
                or r.startswith("//!") or r.startswith("/*!"))


def _strip_markers(raw, kind):
    lines = raw.split("\n")
    out = []
    for idx, ln in enumerate(lines):
        s = ln.strip()
        if kind == "block":
            if idx == 0:
                s = re.sub(r"^(/\*+!?|<!--)", "", s)
            if idx == len(lines) - 1:
                s = re.sub(r"(\*+/|-->)\s*$", "", s)
            s = re.sub(r"^\*+\s?", "", s)
        elif kind == "docstring":
            s = re.sub(r"^[rRbBuUfF]*(\"\"\"|''')", "", s)
            s = re.sub(r"(\"\"\"|''')\s*$", "", s)
        else:
            s = re.sub(r"^(//+!?|#+|--+)\s?", "", s)
        out.append(s.strip())
    return out


def build_units(path, text):
    ext = os.path.splitext(path)[1].lower()
    base = os.path.basename(path)
    lines = text.split("\n")
    raw_spans = []

    if ext in (".py", ".pyi"):
        toks = extract_python(text)
        if toks is not None:
            for (sr, sc), (er, ec), kind, s in toks:
                raw_spans.append((sr, sc, er, s, kind))
    if not raw_spans:
        prof = EXT_PROFILE.get(ext) or NAME_PROFILE.get(base)
        if prof is None:
            return None
        starts = _line_index(text)
        for so, eo, kind in extract_generic(text, prof):
            sr, sc = _pos(starts, so)
            er, _ = _pos(starts, max(so, eo - 1))
            raw_spans.append((sr, sc, er, text[so:eo], kind))

    raw_spans.sort(key=lambda s: (s[0], s[1]))
    units = []
    for sr, sc, er, raw, kind in raw_spans:
        before = lines[sr - 1][:sc] if sr - 1 < len(lines) else ""
        trailing = bool(before.strip())
        indent = len(before) - len(before.lstrip()) if not trailing else 0
        u = Unit(sr, er, kind, raw, _strip_markers(raw, kind), indent, trailing)
        u.own_code = before.strip()
        # Consecutive line comments at the same indent read as one paragraph; judge them
        # as one, or a five-line block gets reported five times.
        if (units and kind == "line" and not trailing and units[-1].kind == "line"
                and not units[-1].trailing and units[-1].end == sr - 1
                and units[-1].indent == indent):
            prev = units[-1]
            prev.end = er
            prev.raw += "\n" + raw
            prev.lines += u.lines
            continue
        units.append(u)

    for pos, u in enumerate(units):
        # A header is the first comment with no real code above it — only blanks, a shebang,
        # or a file-opening tag. A comment merely near the top is not a header.
        u.file_header = pos == 0 and not u.trailing and all(
            not lines[i].strip() or PROLOGUE_RE.match(lines[i])
            for i in range(u.start - 1))
        blanks = 0
        for ln in range(u.end, len(lines)):
            body = lines[ln].strip()
            if not body:
                blanks += 1
                continue
            u.next_code = (ln + 1, lines[ln])
            u.blank_before_code = blanks
            break
        head = u.text
        u.protected = (
            bool(PRAGMA_RE.match(head))
            or u.raw.lstrip().startswith(RAW_PRAGMA_PREFIXES)
            or (u.start <= 6 and bool(LICENCE_RE.search(u.raw)))
        )
    return units


