def self_test():
    import tempfile
    failures = []
    cfg = {"max_words": DEFAULT_MAX_WORDS, "grade": DEFAULT_GRADE, "python_mood": "consistent"}
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, expect, forbid in FIXTURES:
            path = os.path.join(tmp, name)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(src)
            res, why = scan_file(path, set(ALL_RULES), cfg)
            if res is None:
                failures.append("%s: not scanned (%s)" % (name, why))
                continue
            got = {f["rule"] for f in res["findings"]}
            missing = expect - got
            leaked = got & set(forbid)
            if missing:
                failures.append("%s: expected %s, got %s" % (name, sorted(missing), sorted(got)))
            if leaked:
                failures.append("%s: false positive %s" % (name, sorted(leaked)))
            for f in res["findings"]:
                if f["rule"] == "SECRET" and f["excerpt"] != "<redacted>":
                    failures.append("%s: SECRET finding echoed the value" % name)
            if name == "term_code.js" and any(f["rule"] == "TERM"
                                              and f["disposition"] != "ESCALATE"
                                              for f in res["findings"]):
                failures.append("term_code.js: a term that names code must ESCALATE")
            if name in ("spanish.js", "arabic.py") and res["non_english"] != 1:
                failures.append("%s: non-English comment not counted" % name)

    for f in failures:
        print("FAIL  " + f, file=sys.stderr)
    if failures:
        print("\n%d/%d fixtures failed" % (len(failures), len(FIXTURES)), file=sys.stderr)
        return 1
    print("scan-prose self-test: %d fixtures passed" % len(FIXTURES))
    return 0


