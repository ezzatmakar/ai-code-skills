def _line_index(text):
    starts = [0]
    for m in re.finditer("\n", text):
        starts.append(m.end())
    return starts


def _pos(starts, off):
    ln = bisect_right(starts, off)
    return ln, off - starts[ln - 1]


def _regex_allowed(text, i):
    """True when a `/` at offset i starts a JS regex literal rather than division."""
    j = i - 1
    while j >= 0 and text[j] in " \t\r\n":
        j -= 1
    if j < 0:
        return True
    if text[j] in "=(,:[!&|?{};+-*%~^<>":
        return True
    k = j
    while k >= 0 and (text[k].isalnum() or text[k] == "_"):
        k -= 1
    return text[k + 1:j + 1] in {
        "return", "typeof", "instanceof", "in", "of", "new", "delete", "void", "throw",
        "case", "do", "else", "yield", "await",
    }


def _skip_string(text, i, prof):
    """If a string literal starts at i, return the offset just past it, else None."""
    n = len(text)
    for opener, closer, escapes in prof.strings:
        if text.startswith(opener, i):
            j = i + len(opener)
            while j < n:
                c = text[j]
                if escapes and c == "\\":
                    j += 2
                    continue
                if c == "\n" and opener in ("'", '"'):
                    return j          # unterminated line string; resync at the newline
                if text.startswith(closer, j):
                    return j + len(closer)
                j += 1
            return n
    if prof.template and text[i] == "`":
        j, depth = i + 1, 0
        while j < n:
            c = text[j]
            if c == "\\":
                j += 2
                continue
            if text.startswith("${", j):
                depth += 1
                j += 2
                continue
            if c == "}" and depth:
                depth -= 1
            elif c == "`" and not depth:
                return j + 1
            j += 1
        return n
    return None


def _skip_regex(text, i):
    n, j, in_class = len(text), i + 1, False
    while j < n:
        c = text[j]
        if c == "\\":
            j += 2
            continue
        if c == "\n":
            return None
        if c == "[":
            in_class = True
        elif c == "]":
            in_class = False
        elif c == "/" and not in_class:
            j += 1
            while j < n and text[j].isalpha():
                j += 1
            return j
        j += 1
    return None


def extract_generic(text, prof):
    """Comment spans as (start_off, end_off, kind), string- and regex-aware."""
    spans, n, i = [], len(text), 0
    while i < n:
        c = text[i]
        if c in " \t\r\n":
            i += 1
            continue
        s = _skip_string(text, i, prof)
        if s is not None:
            i = s
            continue
        hit = None
        for opener, closer in prof.block:
            if text.startswith(opener, i):
                end = text.find(closer, i + len(opener))
                end = n if end == -1 else end + len(closer)
                hit = (i, end, "block")
                break
        if hit:
            spans.append(hit)
            i = hit[1]
            continue
        for marker in prof.line:
            if text.startswith(marker, i):
                end = text.find("\n", i)
                end = n if end == -1 else end
                hit = (i, end, "line")
                break
        if hit:
            spans.append(hit)
            i = hit[1]
            continue
        if prof.regex and c == "/" and _regex_allowed(text, i):
            r = _skip_regex(text, i)
            if r:
                i = r
                continue
        i += 1
    return spans


def extract_python(text):
    """Python comments and docstrings via tokenize, which never misreads a string."""
    out = []
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, IndentationError, SyntaxError, ValueError):
        return None
    at_stmt_start = True
    for tok in toks:
        if tok.type == tokenize.COMMENT:
            out.append((tok.start, tok.end, "line", tok.string))
        elif tok.type == tokenize.STRING:
            if at_stmt_start and tok.string.lstrip("rRbBuUfF")[:3] in ('"""', "'''"):
                out.append((tok.start, tok.end, "docstring", tok.string))
            at_stmt_start = False
        elif tok.type in (tokenize.NEWLINE, tokenize.NL, tokenize.INDENT,
                          tokenize.DEDENT, tokenize.ENCODING):
            at_stmt_start = True
        elif tok.type != tokenize.COMMENT:
            at_stmt_start = False
    return out


