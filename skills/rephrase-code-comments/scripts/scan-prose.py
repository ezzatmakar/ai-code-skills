def main(argv):
    ap = argparse.ArgumentParser(add_help=True, description=__doc__.split("\n")[0])
    ap.add_argument("paths", nargs="*", default=None,
                    help="files or directories to scan (default: repository root)")
    ap.add_argument("--json", action="store_true", help="emit JSON instead of a table")
    ap.add_argument("--rules", default="", help="comma-separated rule IDs to report")
    ap.add_argument("--since", metavar="REF",
                    help="only files changed since a git ref (e.g. origin/main), plus "
                         "uncommitted and untracked files")
    ap.add_argument("--max-words", type=int, default=DEFAULT_MAX_WORDS,
                    help="sentence word limit (default %d)" % DEFAULT_MAX_WORDS)
    ap.add_argument("--grade", type=int, default=DEFAULT_GRADE,
                    help="Flesch-Kincaid grade limit (default %d)" % DEFAULT_GRADE)
    ap.add_argument("--python-mood", choices=("consistent", "imperative", "descriptive"),
                    default="consistent",
                    help="docstring summary mood for Python (default: match the file)")
    ap.add_argument("--summary-only", action="store_true", help="totals only, no per-file list")
    ap.add_argument("--max-per-file", type=int, default=25, help="findings shown per file")
    ap.add_argument("--self-test", action="store_true", help="run the built-in fixtures")
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()

    rules = set(ALL_RULES)
    if args.rules:
        asked = {r.strip().upper() for r in args.rules.split(",") if r.strip()}
        unknown = asked - rules
        if unknown:
            print("unknown rule(s): %s" % ", ".join(sorted(unknown)), file=sys.stderr)
            return 0
        rules = asked
    cfg = {"max_words": args.max_words, "grade": args.grade, "python_mood": args.python_mood}

    paths = args.paths or ["."]
    root = os.getcwd()
    try:
        top = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                             text=True, timeout=30)
        if top.returncode == 0 and top.stdout.strip():
            root = top.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass

    files = discover(paths, root)
    if args.since:
        changed = changed_files(args.since, root)
        if changed is None:
            print("could not diff against %r — is it a valid git ref?" % args.since,
                  file=sys.stderr)
            return 0
        files = [f for f in files if os.path.abspath(f) in changed]

    results, totals, skipped = [], {}, {}
    comments = prose = non_english = flagged = files_with = 0
    for path in files:
        res, why = scan_file(path, rules, cfg)
        if res is None:
            skipped[why] = skipped.get(why, 0) + 1
            continue
        comments += res["comments"]
        prose += res["prose"]
        non_english += res["non_english"]
        flagged += res["flagged"]
        if res["findings"]:
            files_with += 1
            for f in res["findings"]:
                totals[f["rule"]] = totals.get(f["rule"], 0) + 1
        results.append((path, res))

    stats = {"files": len(results), "files_with_findings": files_with, "comments": comments,
             "prose": prose, "flagged": flagged, "non_english": non_english,
             "skipped": skipped}

    if args.json:
        print(json.dumps({
            "version": 1,
            "root": root,
            "config": cfg,
            "stats": stats,
            "totals": totals,
            "dispositions": DISPOSITION,
            "files": [{"path": os.path.relpath(p, root), "comments": r["comments"],
                       "findings": r["findings"]}
                      for p, r in results if r["findings"]],
        }, indent=2, ensure_ascii=False))
    else:
        print(render(results, totals, stats, root, args.summary_only, args.max_per_file))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        sys.exit(130)
    except BrokenPipeError:           # output piped into `head`
        sys.stderr.close()
        sys.exit(0)
