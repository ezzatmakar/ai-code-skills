def _first_word(text):
    m = re.match(r"\s*([A-Za-z]+)", text)
    return m.group(1) if m else ""


def summary_mood(text):
    """'imperative', 'descriptive', or None for a doc summary's first word."""
    w = _first_word(text).lower()
    if w in THIRD_PERSON:
        return "descriptive"
    if w in VERB_BASES:
        return "imperative"
    return None


FUNC_DECL_RE = re.compile(r"\bfunction\b|=>|\bfunc\b|\bfn\b|\bdef\b|\bsub\b|"
                          r"^\s*(?:[\w<>\[\],.?]+\s+)*[\w$]+\s*\([^;]*$")
TYPE_DECL_RE = re.compile(r"\b(class|interface|enum|struct|trait|protocol|record|object|"
                          r"type\s+\w+\s*=|namespace|module)\b")


def doc_target(unit, lines, ext):
    """'function', 'type', or 'other': what a doc comment documents.

    Mood rules (PEP 257's imperative, Javadoc's third person) govern function and method
    summaries. Class and module docs describe an entity, so their mood is never judged.
    """
    if unit.kind == "docstring":
        i = unit.start - 2
        while i >= 0 and not lines[i].strip():
            i -= 1
        prev = lines[i].strip() if i >= 0 else ""
        if prev.startswith(("def ", "async def ")) or re.search(r"\)\s*(->[^:]+)?:\s*$", prev):
            return "function"
        return "type" if prev.startswith("class ") else "other"
    code = unit.next_code[1] if unit.next_code else ""
    if TYPE_DECL_RE.search(code):
        return "type"
    return "function" if FUNC_DECL_RE.search(code) else "other"


def check_unit(unit, ext, cfg, lines=None):
    findings, seen = [], set()

    def add(rule, line, excerpt, why, suggest=""):
        key = (rule, line, why)
        if key in seen:
            return
        seen.add(key)
        findings.append({
            "rule": rule, "line": line, "disposition": DISPOSITION[rule],
            "excerpt": excerpt[:160], "why": why, "suggest": suggest,
        })

    for label, rx in SECRET_PATTERNS:
        if rx.search(unit.raw) and not SECRET_FALSE_POSITIVE_RE.search(rx.search(unit.raw)
                                                                        .group(0)):
            add("SECRET", unit.start, "<redacted>",
                "possible %s — do not rephrase; rotate the value" % label)
            return findings, None

    paras = paragraphs(unit, ext)
    if not paras:
        return findings, None
    prose = " ".join(p.text for p in paras)
    if not is_english(prose):
        return findings, "non-english"

    for p in paras:
        text = p.text

        def scan(table, rule, flags_first=False):
            for rx, suggest in table:
                for m in rx.finditer(text):
                    if m.group(0).strip() in ("", PLACEHOLDER):
                        continue
                    ln, orig = p.line_at(m.start())
                    add(rule, ln, orig, "'%s'" % m.group(0).strip(), suggest)

        scan(WORDY, "WORDY")
        scan(FILLER, "FILLER")
        scan(HEDGE, "HEDGE")
        scan(NARRATE, "NARRATE")
        scan(VAGUE, "VAGUE")
        scan(TIME, "TIME")
        for sent in sentences(text):
            off = text.find(sent)
            for rx, suggest in AI_WORDS:
                for m in rx.finditer(sent):
                    ln, orig = p.line_at(max(0, off) + m.start())
                    add("AI", ln, orig, "'%s'" % m.group(0).strip(), suggest)
        if EMOJI_RE.search(text):
            ln, orig = p.line_at(EMOJI_RE.search(text).start())
            add("AI", ln, orig, "emoji in a comment", "drop it — say it in words")
        for sent in sentences(text):
            if sent.count("—") >= 2:
                ln, orig = p.line_at(max(0, text.find(sent)))
                add("AI", ln, orig, "%d em dashes in one sentence" % sent.count("—"),
                    "split it, or use commas and parentheses")

        for rx, suggest in TERMS:
            for m in rx.finditer(text):
                ln, orig = p.line_at(m.start())
                term = m.group(0).lower().split()[0].replace("-", "")
                code = ((unit.next_code[1] if unit.next_code else "") + " " + unit.own_code)
                if term[:5] in re.sub(r"[^a-z]", "", code.lower()):
                    add("TERM", ln, orig, "'%s' also names code nearby" % m.group(0),
                        "rename in code first (ESCALATE), then the comment")
                    findings[-1]["disposition"] = "ESCALATE"
                else:
                    add("TERM", ln, orig, "'%s'" % m.group(0), suggest)

        for m in WORD_RE.finditer(text):
            fix = MISSPELLINGS.get(m.group(0).lower())
            if fix:
                ln, orig = p.line_at(m.start())
                add("SPELL", ln, orig, "'%s'" % m.group(0), fix)

        for m in SHOUT_RUN_RE.finditer(text):
            words = [w.strip("!?.,:") for w in m.group(0).split()]
            loud = [w for w in words if w not in ACRONYMS and not w.isdigit()]
            if len(loud) >= 2:
                ln, orig = p.line_at(m.start())
                add("SHOUT", ln, orig, "'%s'" % m.group(0).strip(),
                    "state the rule and the reason in sentence case")
        for m in BANG_RE.finditer(text):
            ln, orig = p.line_at(m.start())
            add("SHOUT", ln, orig, "'%s'" % m.group(0), "one period is enough")

        for m in NEG_RE.finditer(text):
            ln, orig = p.line_at(m.start())
            add("NEG", ln, orig, "'%s'" % m.group(0), "say it positively")

        for m in PASSIVE_RE.finditer(text):
            ln, orig = p.line_at(m.start())
            add("PASSIVE", ln, orig, "'%s'" % m.group(0),
                "active voice: '%s <verb>s …'" % m.group(3))

        for sent in sentences(text):
            n = word_count(sent)
            if n > cfg["max_words"]:
                ln, orig = p.line_at(max(0, text.find(sent)))
                add("LONG", ln, orig, "%d words (limit %d)" % (n, cfg["max_words"]),
                    "split it — one idea per sentence")
                # A few words over is a judgment call; far over is a rewrite.
                if n <= cfg["max_words"] + 10:
                    findings[-1]["disposition"] = "REVIEW"

    first = paras[0]
    if OPENER_RE.match(first.text):
        m = OPENER_RE.match(first.text)
        add("OPENER", first.linenos[0], first.originals[0], "'%s'" % m.group(0).strip(),
            "start with the verb or the fact: 'Parses …', 'Retries because …'")

    words = word_count(prose)
    if words >= MIN_WORDS_FOR_GRADE:
        g = fk_grade([sent for p in paras for sent in sentences(p.text)])
        if g > cfg["grade"]:
            add("READ", unit.start, first.originals[0],
                "grade %.1f over %d words (limit %d)" % (g, words, cfg["grade"]),
                "shorter sentences and shorter words")

    mood = None
    if unit.is_doc:
        summary = first.originals[0]
        stripped_summary = TAG_PREFIX_RE.sub("", summary) if summary.startswith("@") else summary
        is_function = lines is None or doc_target(unit, lines, ext) == "function"
        mood = (summary_mood(stripped_summary)
                if not summary.startswith("@") and is_function else None)
        if ext in THIRD_PERSON_EXTS and mood == "imperative":
            w = _first_word(stripped_summary)
            add("MOOD", first.linenos[0], summary, "'%s' is imperative" % w,
                "third person: '%s'" % _third_person(w.lower()).capitalize())
        if not summary.startswith("@"):
            fw = re.match(r"\s*(\S+)", summary)
            if (fw and fw.group(1)[:1].islower() and fw.group(1).isalpha()
                    and fw.group(1) not in LOWERCASE_NAMES
                    and not re.search(r"→|->|[{|]", summary) and ext != ".go"):
                add("FORMAT", first.linenos[0], summary,
                    "summary starts lowercase", "capitalize the first word")
            last_para_line = first.originals[-1].rstrip()
            if (ext in PERIOD_EXTS and len(paras) >= 1 and word_count(first.text) >= 3
                    and not re.search(r"[.!?:)`\]]$", last_para_line)):
                add("FORMAT", first.linenos[-1], last_para_line,
                    "summary has no closing period", "end the sentence with a period")

    if ext == ".go" and unit.kind == "line" and not unit.trailing and unit.next_code \
            and unit.blank_before_code == 0:
        dm = GO_DECL_RE.match(unit.next_code[1])
        if dm:
            name = dm.group(1)
            head = first.originals[0]
            if not re.match(r"^(?:(?:A|An|The)\s+)?%s\b" % re.escape(name), head) \
                    and not head.startswith("Deprecated"):
                add("MOOD", first.linenos[0], head, "Go doc comment does not start with '%s'"
                    % name, "'%s …' — name the symbol first" % name)

    return findings, mood


def apply_file_mood(moods, ext, py_mood):
    """Flag doc summaries that break the mood the rest of the file uses.

    `moods` is a list of (unit, "imperative" | "descriptive"). Third-person languages and Go
    are judged per unit in check_unit, against their own style authority.
    """
    if ext in THIRD_PERSON_EXTS or ext == ".go":
        return []
    imp = sum(1 for _, m in moods if m == "imperative")
    desc = len(moods) - imp
    if ext in (".py", ".pyi") and py_mood in ("imperative", "descriptive"):
        target = py_mood
    elif imp and desc:
        if imp == desc:
            target = "imperative" if ext in (".py", ".pyi") else "descriptive"
        else:
            target = "imperative" if imp > desc else "descriptive"
    else:
        return []
    out = []
    for unit, m in moods:
        if m == target:
            continue
        summary = next((x for x in unit.lines if x), "")
        w = _first_word(summary)
        fix = (THIRD_PERSON.get(w.lower(), w.lower()) if target == "imperative"
               else _third_person(w.lower()))
        out.append({
            "rule": "MOOD", "line": unit.start, "disposition": DISPOSITION["MOOD"],
            "excerpt": summary[:160],
            "why": "'%s' is %s; this file is %s" % (w, m, target),
            "suggest": "'%s'" % fix.capitalize(),
        })
    return out


def scan_file(path, rules, cfg):
    try:
        if os.path.getsize(path) > MAX_FILE_BYTES:
            return None, "too large"
        with open(path, "r", encoding="utf-8", errors="strict") as fh:
            text = fh.read()
    except (OSError, UnicodeDecodeError):
        return None, "unreadable"
    head = "\n".join(text.split("\n", 40)[:40])
    if GENERATED_FILE_RE.search(head):
        return None, "generated"
    if VENDORED_RE.search(text[:600]):
        return None, "vendored"
    if any(len(ln) > 500 for ln in text.split("\n")[:50]):
        return None, "minified"
    units = build_units(path, text)
    if units is None:
        return None, "unsupported"
    ext = os.path.splitext(path)[1].lower()
    src_lines = text.split("\n")
    findings, moods = [], []
    prose = non_english = flagged = 0
    for u in units:
        if u.protected:
            continue
        if sum(1 for ln in u.lines if ln and _code_like(ln) >= 2) > len(u.lines) / 2:
            continue            # commented-out code is comment-cleanup's job, not ours
        got, mood = check_unit(u, ext, cfg, src_lines)
        if mood == "non-english":
            non_english += 1
            continue
        if any(ln for ln in u.lines):
            prose += 1
        if mood in ("imperative", "descriptive"):
            moods.append((u, mood))
        kept = [f for f in got if f["rule"] in rules]
        if kept:
            flagged += 1
        findings += kept
    if "MOOD" in rules:
        extra = apply_file_mood(moods, ext, cfg["python_mood"])
        flagged_lines = {f["line"] for f in findings}
        flagged += sum(1 for f in extra if f["line"] not in flagged_lines)
        findings += extra
    findings.sort(key=lambda f: (f["line"], f["rule"]))
    return {"comments": len(units), "prose": prose, "non_english": non_english,
            "flagged": flagged, "findings": findings}, None


def changed_files(ref, root):
    """Files that differ from `ref`, including uncommitted and untracked ones."""
    names = set()
    for cmd in (["git", "-C", root, "diff", "--name-only", "--diff-filter=ACMR", ref],
                ["git", "-C", root, "ls-files", "--others", "--exclude-standard"]):
        try:
            out = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            return None
        if out.returncode != 0:
            return None
        names |= {os.path.join(root, n) for n in out.stdout.splitlines() if n}
    return names


