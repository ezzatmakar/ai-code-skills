#!/usr/bin/env python3
"""Flag code comments whose wording is wordy, vague, robotic, or hard to read.

A repo-wide rewording pass cannot start by reading every file: the context window runs out
first. This script does the mechanical pass. It finds every English prose comment, checks its
wording against the style rules, and emits a work list the agent can act on file by file.

It judges wording only. Whether a comment should exist, how long it is, and where it sits
belong to the comment-cleanup skill. Every finding is a *candidate*, not a verdict: the
heuristics cannot read intent, so the agent must open the file and decide. Rule IDs match
references/REWRITE_RULES.md.

Usage:
    scan-prose.py [paths...] [--json] [--rules ID,ID] [--since REF] [--summary-only]
                  [--max-words N] [--grade N]
    scan-prose.py --self-test

Exits 0 for any scan result, including findings — this reports, it never gates.
--self-test exits non-zero on failure so it can be wired into a test suite.
"""

