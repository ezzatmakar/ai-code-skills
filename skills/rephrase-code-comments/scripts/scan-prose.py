def _clip(s, n):
    s = " ".join(s.split())
    return s if len(s) <= n else s[:n - 1] + "…"


def render(results, totals, stats, root, summary_only, max_per_file):
    out = []
    if not summary_only:
        for path, res in results:
            if not res["findings"]:
                continue
            out.append(os.path.relpath(path, root))
            shown = res["findings"][:max_per_file]
            for f in shown:
                tail = "  → %s" % f["suggest"] if f["suggest"] else ""
                out.append("  %5d  %-8s %-9s %s%s" % (f["line"], f["rule"], f["disposition"],
                                                      f["why"], tail))
                if f["rule"] != "SECRET":
                    out.append("  %5s  %s" % ("", _clip(f["excerpt"], 96)))
            if len(res["findings"]) > len(shown):
                out.append("  ... %d more in this file" % (len(res["findings"]) - len(shown)))
            out.append("")
    pct = (100.0 * stats["flagged"] / stats["prose"]) if stats["prose"] else 0.0
    out.append("── prose scan " + "─" * 46)
    out.append("  files scanned        %d" % stats["files"])
    out.append("  files with findings  %d" % stats["files_with_findings"])
    out.append("  comments             %d" % stats["comments"])
    out.append("  English prose        %d" % stats["prose"])
    out.append("  needing a rewrite    %d (%.0f%%)" % (stats["flagged"], pct))
    out.append("  findings             %d" % sum(totals.values()))
    if stats["non_english"]:
        out.append("  non-English (kept)   %d — never translated" % stats["non_english"])
    if stats["skipped"]:
        out.append("  skipped files        %d (%s)"
                   % (sum(stats["skipped"].values()),
                      ", ".join("%s: %d" % kv for kv in sorted(stats["skipped"].items()))))
    if totals:
        out.append("")
        for rule, n in sorted(totals.items(), key=lambda kv: (-kv[1], kv[0])):
            out.append("  %-8s %5d  %-9s %s" % (rule, n, DISPOSITION[rule], RULE_HELP[rule]))
    out.append("")
    out.append("  Candidates, not verdicts — open each file and decide.")
    out.append("  Rule IDs map to references/REWRITE_RULES.md.")
    return "\n".join(out)


