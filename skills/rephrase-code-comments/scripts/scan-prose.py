def discover(paths, root):
    files, seen = [], set()

    def want(p):
        base = os.path.basename(p)
        if SKIP_FILE_RE.search(base):
            return False
        ext = os.path.splitext(p)[1].lower()
        return ext in EXT_PROFILE or base in NAME_PROFILE

    for p in paths:
        if os.path.isfile(p):
            if want(p) and p not in seen:
                seen.add(p)
                files.append(p)
            continue
        listed = None
        try:
            # Include untracked files: a pass over "my changes" must see new, unstaged files.
            out = subprocess.run(["git", "-C", p, "ls-files", "-z", "--cached", "--others",
                                  "--exclude-standard"], capture_output=True, text=True,
                                 timeout=60)
            if out.returncode == 0:
                listed = [os.path.join(p, f) for f in out.stdout.split("\0") if f]
        except (OSError, subprocess.SubprocessError):
            listed = None
        if listed is None:
            listed = []
            for dirpath, dirnames, filenames in os.walk(p):
                dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS
                               and not d.startswith(".")]
                listed += [os.path.join(dirpath, f) for f in filenames]
        for f in listed:
            rel = os.path.relpath(f, root)
            if any(part in SKIP_DIRS for part in rel.split(os.sep)):
                continue
            if want(f) and f not in seen:
                seen.add(f)
                files.append(f)
    return sorted(files)


