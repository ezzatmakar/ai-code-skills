class Paragraph:
    """Masked prose from consecutive comment lines, with a map back to source lines."""

    def __init__(self):
        self.text = ""
        self.starts = []        # offset in text where each source line begins
        self.linenos = []
        self.originals = []

    def add(self, lineno, masked, original):
        if self.text:
            self.text += " "
        self.starts.append(len(self.text))
        self.linenos.append(lineno)
        self.originals.append(original)
        self.text += masked

    def line_at(self, off):
        i = max(0, bisect_right(self.starts, off) - 1)
        return self.linenos[i], self.originals[i]


def mask(s):
    s = CODE_SPAN_RE.sub(PLACEHOLDER, s)
    s = QUOTED_RE.sub(PLACEHOLDER, s)
    s = URL_RE.sub(PLACEHOLDER, s)
    s = IDENT_RE.sub(PLACEHOLDER, s)
    return s


def paragraphs(unit, ext):
    """Split a comment unit into prose paragraphs, skipping code, examples, and tags."""
    out, cur, in_fence, in_example = [], Paragraph(), False, False

    def flush():
        nonlocal cur
        if cur.text.strip():
            out.append(cur)
        cur = Paragraph()

    for idx, line in enumerate(unit.lines):
        lineno = unit.start + idx
        s = line.strip()
        if FENCE_RE.match(s):
            in_fence = not in_fence
            flush()
            continue
        if in_fence or not s:
            flush()
            continue
        low = s.lower()
        if low.startswith("@example") or SECTION_RE.match(s) and s.lower().startswith("example"):
            in_example = True
            flush()
            continue
        if in_example:
            if s.startswith("@") or SECTION_RE.match(s):
                in_example = False
            else:
                continue
        if SECTION_RE.match(s):
            flush()
            continue
        if DOCTEST_RE.match(s) or _code_like(s) >= 2 or MARKER_RE.fullmatch(s):
            flush()
            continue
        body = s
        if body.startswith("@") or body.startswith(":") or (
                unit.kind == "docstring" and re.match(r"^[\w*]+(\s*\([^)]*\))?:\s", body)):
            flush()
            body = TAG_PREFIX_RE.sub("", body, count=1)
            if not body.strip():
                continue
        # An aligned column or a `|` continuation is a table row, not part of a sentence.
        row = bool(COLUMN_RE.search(body) or body.startswith("|"))
        if BULLET_RE.match(body) or row:
            flush()
            body = BULLET_RE.sub("", body)
        body = MARKER_RE.sub("", body).strip()
        if body:
            cur.add(lineno, mask(body), s)
        if row:
            flush()
    flush()
    return out


def is_english(text):
    alpha = [c for c in text if c.isalpha()]
    if len(alpha) < 12:
        return True
    non_latin = sum(1 for c in alpha if ord(c) > 0x24F)
    if non_latin / len(alpha) > 0.3:
        return False
    words = [w.lower() for w in WORD_RE.findall(text)]
    if len(words) < 6:
        return True
    en = sum(1 for w in words if w in EN_STOP)
    fr = sum(1 for w in words if w in FOREIGN_STOP)
    return not (fr >= 2 and fr > en and fr / len(words) > 0.12)


def sentences(text):
    protected = ABBREV_RE.sub(lambda m: m.group(0).replace(".", "․"), text)
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(\[X])|;\s+", protected)
    return [p.replace("․", ".").strip() for p in parts if p.strip()]


def word_count(s):
    return len(WORD_RE.findall(s))


def syllables(word):
    w = word.lower().strip("'")
    if len(w) <= 3:
        return 1
    w = re.sub(r"(?:es|ed|e)$", "", w) or w
    groups = re.findall(r"[aeiouy]+", w)
    return max(1, len(groups))


def fk_grade(sents):
    """Flesch-Kincaid grade over pre-split sentences; paragraphs never merge into one."""
    words = [w for sent in sents for w in WORD_RE.findall(sent)]
    if not sents or not words:
        return 0.0
    syl = sum(syllables(w) for w in words)
    return 0.39 * (len(words) / len(sents)) + 11.8 * (syl / len(words)) - 15.59


