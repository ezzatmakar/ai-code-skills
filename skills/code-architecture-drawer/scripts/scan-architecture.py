def strip_c_comments(text):
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"(?m)^\s*//.*$", "", text)


def strip_hash_comments(text):
    return re.sub(r"(?m)^\s*#.*$", "", text)


class Resolver:
    """Maps an import specifier to a file in the repo, or to an external package name."""

    def __init__(self, root, files):
        self.root = root
        self.files = set(files)
        self.by_dir = defaultdict(list)
        for f in files:
            self.by_dir[os.path.dirname(f)].append(f)
        self._js_config()
        self._py_index()
        self._go_module()
        self._php_psr4()
        self._jvm_index()
        self._cs_index()

    # -- JavaScript / TypeScript ------------------------------------------------

    def _js_config(self):
        self.js_paths = []          # (prefix, [targets]) from tsconfig/jsconfig paths
        self.js_base = []
        self.workspaces = {}        # package name → dir
        for cfg in sorted(f for f in self.files
                          if os.path.basename(f) in ("tsconfig.json", "jsconfig.json")):
            data = loose_json(read(self.root, cfg)) or {}
            opts = data.get("compilerOptions") or {}
            base = os.path.normpath(os.path.join(os.path.dirname(cfg), opts.get("baseUrl", ".")))
            if opts.get("baseUrl"):
                self.js_base.append(base)
            for alias, targets in (opts.get("paths") or {}).items():
                prefix = alias.rstrip("*")
                tg = [os.path.normpath(os.path.join(base, t.rstrip("*"))) for t in targets]
                self.js_paths.append((prefix, tg, alias.endswith("*")))
        self.js_paths.sort(key=lambda p: -len(p[0]))
        for pj in (f for f in self.files if os.path.basename(f) == "package.json"):
            if pj == "package.json":
                continue
            data = loose_json(read(self.root, pj)) or {}
            if data.get("name"):
                self.workspaces[data["name"]] = os.path.dirname(pj)

    def _js_file(self, base):
        base = os.path.normpath(base)
        if base in self.files and not base.endswith(".json"):
            return base
        for ext in JS_EXTS:
            if base + ext in self.files:
                return base + ext
        stem, ext = os.path.splitext(base)
        if ext in (".js", ".mjs", ".cjs", ".jsx"):          # TS ESM imports name the .js output
            for alt in (".ts", ".tsx", ".mts", ".cts"):
                if stem + alt in self.files:
                    return stem + alt
        for ext in JS_EXTS:
            if os.path.join(base, "index" + ext) in self.files:
                return os.path.join(base, "index" + ext)
        return None

    def resolve_js(self, src, spec):
        spec = spec.split("?")[0]
        if spec.startswith("."):
            hit = self._js_file(os.path.join(os.path.dirname(src), spec))
            return ("file", hit) if hit else (None, None)
        for prefix, targets, star in self.js_paths:
            if (star and spec.startswith(prefix)) or spec == prefix:
                rest = spec[len(prefix):] if star else ""
                for t in targets:
                    hit = self._js_file(os.path.join(t, rest))
                    if hit:
                        return "file", hit
        for name, d in self.workspaces.items():
            if spec == name or spec.startswith(name + "/"):
                rest = spec[len(name):].lstrip("/")
                hit = self._js_file(os.path.join(d, rest or "index"))
                if not hit:
                    for guess in ("src/index", "index", "src/main", "lib/index"):
                        hit = self._js_file(os.path.join(d, guess))
                        if hit:
                            break
                return ("file", hit) if hit else ("pkg", name)
        for base in self.js_base:
            hit = self._js_file(os.path.join(base, spec))
            if hit:
                return "file", hit
        if spec.startswith(("node:", "bun:", "deno:")) or spec in NODE_BUILTINS:
            return None, None
        parts = spec.split("/")
        name = "/".join(parts[:2]) if spec.startswith("@") else parts[0]
        return "ext", name

    # -- Python ------------------------------------------------------------------

    def _py_index(self):
        self.py_mods = {}
        roots = {""} | {r for r in ("src", "lib", "app") if any(
            f.startswith(r + "/") for f in self.files)}
        for f in self.files:
            if not f.endswith(".py"):
                continue
            for r in roots:
                if r and not f.startswith(r + "/"):
                    continue
                rel = f[len(r) + 1:] if r else f
                mod = rel[:-3].replace("/", ".")
                if mod.endswith(".__init__"):
                    mod = mod[:-9]
                self.py_mods.setdefault(mod, f)

    def resolve_py(self, src, module, names):
        out = []
        if module.startswith("."):
            dots = len(module) - len(module.lstrip("."))
            pkg = os.path.dirname(src).split("/") if os.path.dirname(src) else []
            pkg = pkg[:len(pkg) - (dots - 1)] if dots > 1 else pkg
            base = ".".join(pkg + ([module.lstrip(".")] if module.lstrip(".") else []))
            cands = [base + "." + n for n in names] + [base]
            for c in cands:
                for key in (c, c.split(".", 1)[-1] if "." in c else c):
                    if key in self.py_mods:
                        out.append(("file", self.py_mods[key]))
                        break
            return out[:1] if out else []
        for c in [module + "." + n for n in names] + [module]:
            if c in self.py_mods:
                return [("file", self.py_mods[c])]
        top = module.split(".")[0]
        if top and top not in PY_STDLIB and top != "__future__":
            return [("ext", top)]
        return []

    # -- Go ----------------------------------------------------------------------

    def _go_module(self):
        self.go_mods = []
        for gm in (f for f in self.files if os.path.basename(f) == "go.mod"):
            m = re.search(r"^module\s+(\S+)", read(self.root, gm) or "", re.M)
            if m:
                self.go_mods.append((m.group(1), os.path.dirname(gm)))
        self.go_mods.sort(key=lambda x: -len(x[0]))

    def resolve_go(self, spec):
        for mod, d in self.go_mods:
            if spec == mod or spec.startswith(mod + "/"):
                pkg_dir = os.path.normpath(os.path.join(d, spec[len(mod):].lstrip("/")))
                files = [f for f in self.by_dir.get(pkg_dir if pkg_dir != "." else "", [])
                         if f.endswith(".go") and not f.endswith("_test.go")]
                return ("file", files[0]) if files else (None, None)
        first = spec.split("/")[0]
        if "." not in first:
            return None, None       # standard library
        return "ext", "/".join(spec.split("/")[:3])

    # -- PHP ---------------------------------------------------------------------

    def _php_psr4(self):
        self.psr4 = []
        for cj in (f for f in self.files if os.path.basename(f) == "composer.json"):
            data = loose_json(read(self.root, cj)) or {}
            for sect in ("autoload", "autoload-dev"):
                for ns, dirs in ((data.get(sect) or {}).get("psr-4") or {}).items():
                    for d in (dirs if isinstance(dirs, list) else [dirs]):
                        self.psr4.append((ns, os.path.normpath(os.path.join(
                            os.path.dirname(cj), d))))
        self.psr4.sort(key=lambda x: -len(x[0]))

    def resolve_php(self, fqcn):
        fqcn = fqcn.lstrip("\\")
        for ns, d in self.psr4:
            if fqcn.startswith(ns) or fqcn + "\\" == ns:
                rel = fqcn[len(ns):].replace("\\", "/")
                cand = os.path.normpath(os.path.join(d, rel + ".php"))
                if cand in self.files:
                    return "file", cand
                pkg_dir = os.path.normpath(os.path.join(d, rel))
                files = [f for f in self.by_dir.get(pkg_dir, []) if f.endswith(".php")]
                return ("file", files[0]) if files else (None, None)
        parts = fqcn.split("\\")
        if len(parts) >= 2:
            return "ext", "\\".join(parts[:2])
        return None, None

    # -- Java / Kotlin / Scala ------------------------------------------------------

    def _jvm_index(self):
        self.jvm_classes, self.jvm_pkgs = {}, defaultdict(list)
        for f in self.files:
            if os.path.splitext(f)[1] not in (".java", ".kt", ".kts", ".scala"):
                continue
            m = JVM_PKG_RE.search((read(self.root, f, 200_000) or "")[:4000])
            if m:
                cls = os.path.splitext(os.path.basename(f))[0]
                self.jvm_classes[m.group(1) + "." + cls] = f
                self.jvm_pkgs[m.group(1)].append(f)

    def resolve_jvm(self, name, star):
        if star and name in self.jvm_pkgs:
            return "file", self.jvm_pkgs[name][0]
        probe = name
        while probe:
            if probe in self.jvm_classes:
                return "file", self.jvm_classes[probe]
            probe = probe.rpartition(".")[0]
        if name.split(".")[0] in ("java", "javax", "kotlin", "scala", "jdk", "sun"):
            return None, None
        return "ext", ".".join(name.split(".")[:3])

    # -- C# ------------------------------------------------------------------------

    def _cs_index(self):
        self.cs_ns = defaultdict(list)
        for f in self.files:
            if f.endswith(".cs"):
                for m in CS_NS_RE.finditer((read(self.root, f, 400_000) or "")[:8000]):
                    self.cs_ns[m.group(1)].append(f)

    def resolve_cs(self, ns):
        if ns in self.cs_ns:
            return "file", self.cs_ns[ns][0]
        if ns.split(".")[0] in ("System", "Microsoft"):
            return None, None
        return "ext", ".".join(ns.split(".")[:2])


