def tarjan(nodes, edges):
    """Strongly connected components with more than one node (the cycles)."""
    index, low, on, stack, out = {}, {}, set(), [], []
    counter = [0]
    sys.setrecursionlimit(max(10000, len(nodes) * 4))

    def visit(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in edges.get(v, ()):
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            if len(comp) > 1:
                out.append(sorted(comp))

    for v in sorted(nodes):
        if v not in index:
            visit(v)
    return sorted(out, key=lambda c: -len(c))


def cycle_path(scc, edges):
    """One concrete loop through an SCC, for the report's evidence line."""
    members = set(scc)
    start = scc[0]
    path, seen, node = [start], {start}, start
    while True:
        nxt = next((w for w in sorted(edges.get(node, ())) if w in members and w == start
                    and len(path) > 1), None)
        if nxt:
            return path + [start]
        nxt = next((w for w in sorted(edges.get(node, ())) if w in members and w not in seen),
                   None)
        if not nxt:
            return path + [start]
        path.append(nxt)
        seen.add(nxt)
        node = nxt


