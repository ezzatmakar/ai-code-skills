def _mm_label(s):
    return (s.replace("&", "#amp;").replace('"', "#quot;").replace("<", "#lt;")
            .replace(">", "#gt;"))


def _kloc(n):
    return "%.1fk LOC" % (n / 1000) if n >= 1000 else "%d LOC" % n


# Explicit fills with explicit text colour read the same on GitHub's light and dark themes.
# Plain flowchart syntax only: Mermaid's C4 diagrams are experimental and cannot draw a key.
CLASSDEFS = [
    "classDef comp fill:#1f6feb,stroke:#0b3d91,color:#ffffff",
    "classDef cycle fill:#cf222e,stroke:#82071e,color:#ffffff",
    "classDef ext fill:#6e7781,stroke:#424a53,color:#ffffff",
    "classDef store fill:#8250df,stroke:#512a97,color:#ffffff",
    "classDef person fill:#0969da,stroke:#033d8b,color:#ffffff",
    "classDef other fill:#afb8c1,stroke:#6e7781,color:#1f2328",
]


def _frontmatter(title):
    return ["---", "title: %s" % title.replace(":", " -"), "---"]


def _legend(entries):
    out = ['  subgraph Legend["Legend"]', "    direction LR"]
    for i, (cls, label, shape) in enumerate(entries):
        out.append("    lg%d%s" % (i, shape % _mm_label(label)))
    out.append("  end")
    for i, (cls, _, _) in enumerate(entries):
        out.append("  class lg%d %s" % (i, cls))
    return out


def mermaid_components(res, max_nodes, max_edges=60):
    comps = res["components"]
    cyc = {c for scc in res["cycles"]["components"] for c in scc}
    degree = defaultdict(int)
    for e in res["edges"]:
        degree[e["from"]] += 1
        degree[e["to"]] += 1
    ranked = sorted(comps, key=lambda c: -(comps[c]["loc"] + 400 * degree[c]
                                            + 5000 * (c in cyc)))
    keep = set(ranked[:max_nodes])
    dropped = [c for c in comps if c not in keep]
    ids = {c: "c%d" % i for i, c in enumerate(sorted(keep))}
    scope = res.get("scope") or os.path.basename(res["root"].rstrip("/"))
    lines = _frontmatter("Component dependencies - %s" % scope) + ["flowchart LR"]
    groups = defaultdict(list)
    for c in sorted(keep):
        m = comps[c]
        groups["outside" if m.get("outside_scope") else (m["layer"] or "other")].append(c)
    order = ["presentation", "application", "domain", "infrastructure", "shared", "other",
             "outside"]
    use_groups = len([g for g in groups if g not in ("other", "outside")]) >= 2
    for g in order:
        if g not in groups:
            continue
        boxed = use_groups or g == "outside"
        if boxed:
            title = "Outside this scope" if g == "outside" else g.capitalize()
            lines.append('  subgraph L_%s["%s"]' % (g, title))
        for c in groups[g]:
            m = comps[c]
            detail = ("%d files imported" % m["files"] if m.get("outside_scope")
                      else "%d files, %s" % (m["files"], _kloc(m["loc"])))
            lines.append('    %s["%s<br/>%s"]' % (ids[c], _mm_label(c), detail))
        if boxed:
            lines.append("  end")
    if dropped:
        lines.append('  other["%d smaller components"]' % len(dropped))
    cycle_pairs = {(a, b) for scc in res["cycles"]["components"] for a in scc for b in scc}
    agg = defaultdict(int)
    for e in res["edges"]:
        a = ids.get(e["from"], "other" if dropped else None)
        b = ids.get(e["to"], "other" if dropped else None)
        if not a or not b or a == b:
            continue
        agg[(a, b, (e["from"], e["to"]) in cycle_pairs)] += e["imports"]
    # Readability: every cycle edge stays; the rest keep the heaviest until the cap.
    cyc_edges = [kv for kv in agg.items() if kv[0][2]]
    rest = sorted((kv for kv in agg.items() if not kv[0][2]), key=lambda kv: -kv[1])
    shown = cyc_edges + rest[:max(0, max_edges - len(cyc_edges))]
    hidden = rest[len(shown) - len(cyc_edges):]
    red = []
    for i, ((a, b, is_cycle), n) in enumerate(sorted(shown)):
        lines.append("  %s -->|imports x%d| %s" % (a, n, b))
        if is_cycle:
            red.append(i)
    legend = [("comp", "Component", '["%s"]'), ("cycle", "In a dependency cycle", '["%s"]'),
              ("ext", "Outside scope", '["%s"]')]
    if hidden:
        heaviest = max(n for _, n in hidden)
        legend.append(("other", "%d lighter edges hidden (%s%d import%s each)"
                       % (len(hidden), "at most " if heaviest > 1 else "", heaviest,
                          "s" if heaviest > 1 else ""), '["%s"]'))
    lines += _legend(legend)
    lines += ["  " + c for c in CLASSDEFS]
    normal = [ids[c] for c in keep if c not in cyc and not comps[c].get("outside_scope")]
    if normal:
        lines.append("  class %s comp" % ",".join(sorted(normal)))
    hot = [ids[c] for c in keep if c in cyc]
    if hot:
        lines.append("  class %s cycle" % ",".join(sorted(hot)))
    outside = [ids[c] for c in keep if comps[c].get("outside_scope") and c not in cyc]
    if outside:
        lines.append("  class %s ext" % ",".join(sorted(outside)))
    if dropped:
        lines.append("  class other other")
    if red:
        lines.append("  linkStyle %s stroke:#cf222e,stroke-width:2px"
                     % ",".join(str(i) for i in red))
    return "\n".join(lines)


SHAPES = {"database": '[("%s")]', "cache": '[("%s")]', "queue": '[/"%s"/]',
          "storage": '[("%s")]', "search": '[("%s")]'}
STORE_KINDS = {"database", "cache", "queue", "storage", "search"}
INTENT = {"database": "reads and writes", "cache": "caches in", "queue": "publishes jobs to",
          "storage": "stores files in", "search": "indexes and queries", "payments":
          "charges via", "email": "sends email via", "auth": "authenticates with",
          "observability": "reports errors and traces to", "analytics": "sends events to",
          "ai": "calls", "cms": "reads content from", "realtime": "pushes updates via",
          "flags": "reads flags from"}


def _two_line(first, second):
    return "%s<br/>%s" % (_mm_label(first), _mm_label(second))


def mermaid_containers(res):
    name = os.path.basename(res["root"].rstrip("/")) or "System"
    lines = _frontmatter("Containers - %s (draft from code, verify intents)" % name)
    lines += ["flowchart TB", '  user(["User<br/>Person"])']
    services = res["compose_services"]
    runnable = {n for n, s in services.items() if s["kind"] in ("app", "service", "proxy")}
    lines.append('  subgraph SYS["%s - software system"]' % _mm_label(name))
    ids, klass = {}, {}
    tech = " / ".join(res["frameworks"][:3]) or "application"
    if runnable:
        for i, n in enumerate(sorted(runnable)):
            ids[n] = "a%d" % i
            klass[n] = "comp"
            role = "Reverse proxy" if services[n]["kind"] == "proxy" else "Container"
            lines.append('    %s["%s"]' % (ids[n], _two_line(n, "%s: %s" % (
                role, services[n]["image"] or tech))))
    else:
        ids["app"] = "a0"
        klass["app"] = "comp"
        lines.append('    a0["%s"]' % _two_line("Application", "Container: %s" % tech))
    others = sorted((n, s) for n, s in services.items() if n not in runnable)
    for i, (n, s) in enumerate(others):
        ids[n] = "s%d" % i
        klass[n] = "store" if s["kind"] in STORE_KINDS else "ext"
        shape = SHAPES.get(s["kind"], '["%s"]')
        lines.append("    %s%s" % (ids[n], shape % _two_line(n, s["image"] or s["kind"])))
    lines.append("  end")
    # The user reaches the system through the front proxy (one nothing else depends on),
    # else through the first application container.
    depended = {d for s in services.values() for d in s["depends_on"]}
    fronts = sorted(n for n in runnable if services[n]["kind"] == "proxy" and n not in depended)
    apps = sorted(n for n in runnable if services[n]["kind"] != "proxy")
    entry = ids[fronts[0]] if fronts else (ids[apps[0]] if apps else "a0")
    main_app = ids[apps[0]] if apps else entry
    lines.append('  user -->|"uses (HTTPS)"| %s' % entry)
    for n, s in sorted(services.items()):
        for dep in s["depends_on"]:
            if n in ids and dep in ids:
                if s["kind"] == "proxy":
                    label = "forwards requests to"
                else:
                    label = INTENT.get(services.get(dep, {}).get("kind"), "depends on")
                lines.append('  %s -->|"%s"| %s' % (ids[n], label, ids[dep]))
    k = 0
    covered = {s["kind"] for _, s in others}
    for ename, e in sorted(res["externals"].items()):
        if e["category"] in ("http", "api") or (e["category"] in covered
                                                 and e["category"] in SHAPES):
            continue
        k += 1
        nid = "x%d" % k
        shape = SHAPES.get(e["category"], '["%s"]')
        lines.append("  %s%s" % (nid, shape % _two_line(ename, "External: %s" % e["category"])))
        lines.append('  %s -.->|"%s"| %s' % (main_app, INTENT.get(e["category"], "uses"), nid))
    lines += _legend([("person", "Person", '(["%s"])'),
                      ("comp", "Container (this system)", '["%s"]'),
                      ("store", "Data store", '[("%s")]'),
                      ("ext", "External or dev-only service", '["%s"]')])
    lines += ["  " + c for c in CLASSDEFS]
    lines.append("  class user person")
    for cls in ("comp", "store", "ext"):
        members = [ids[n] for n, c in klass.items() if c == cls]
        if cls == "ext":
            members += ["x%d" % i for i in range(1, k + 1)]
        if members:
            lines.append("  class %s %s" % (",".join(members), cls))
    return "\n".join(lines)


