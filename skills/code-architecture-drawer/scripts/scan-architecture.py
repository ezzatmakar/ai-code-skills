def imports_of(resolver, rel, text, lang):
    """Yield (kind, target) — kind 'file' (repo path) or 'ext' (package name)."""
    out = []
    if lang == "js":
        body = strip_c_comments(text)
        for m in JS_IMPORT_RE.finditer(body):
            spec = m.group(1) or m.group(2) or m.group(3)
            kind, tgt = resolver.resolve_js(rel, spec)
            if kind:
                out.append((kind, tgt))
    elif lang == "py":
        body = strip_hash_comments(text)
        for m in PY_IMPORT_RE.finditer(body):
            if m.group(1) is not None:
                names = [n.strip().split(" as ")[0] for n in
                         m.group(2).replace("(", "").replace(")", "").split(",") if n.strip()]
                out += resolver.resolve_py(rel, m.group(1), names)
            else:
                for mod in m.group(3).split(","):
                    mod = mod.strip().split(" as ")[0].strip()
                    if mod:
                        out += resolver.resolve_py(rel, mod, [])
    elif lang == "go":
        body = strip_c_comments(text)
        specs = GO_IMPORT_ONE_RE.findall(body)
        for blk in GO_IMPORT_BLOCK_RE.findall(body):
            specs += GO_STR_RE.findall(blk)
        for spec in specs:
            kind, tgt = resolver.resolve_go(spec)
            if kind:
                out.append((kind, tgt))
    elif lang == "php":
        body = strip_c_comments(text)
        for m in PHP_USE_RE.finditer(body):
            base, group = m.group(1), m.group(2)
            names = ([base.rstrip("\\") + "\\" + g.strip().split(" as ")[0]
                      for g in group.split(",") if g.strip()] if group else [base])
            for n in names:
                kind, tgt = resolver.resolve_php(n)
                if kind:
                    out.append((kind, tgt))
    elif lang == "jvm":
        for m in JVM_IMPORT_RE.finditer(strip_c_comments(text)):
            kind, tgt = resolver.resolve_jvm(m.group(1), bool(m.group(2)))
            if kind:
                out.append((kind, tgt))
    elif lang == "cs":
        for m in CS_USING_RE.finditer(strip_c_comments(text)):
            kind, tgt = resolver.resolve_cs(m.group(1))
            if kind:
                out.append((kind, tgt))
    elif lang == "rb":
        for m in RB_REQ_RE.finditer(strip_hash_comments(text)):
            spec = m.group(2)
            base = (os.path.join(os.path.dirname(rel), spec) if m.group(1)
                    else os.path.join("lib", spec))
            base = os.path.normpath(base)
            cand = base if base.endswith(".rb") else base + ".rb"
            if cand in resolver.files:
                out.append(("file", cand))
            elif not m.group(1):
                out.append(("ext", spec.split("/")[0]))
    elif lang == "rs":
        body = strip_c_comments(text)
        here = os.path.dirname(rel)
        for m in RS_MOD_RE.finditer(body):
            for cand in (os.path.join(here, m.group(1) + ".rs"),
                         os.path.join(here, m.group(1), "mod.rs")):
                if cand in resolver.files:
                    out.append(("file", cand))
                    break
        crate_src = rel.split("src/")[0] + "src" if "src/" in rel else here
        for m in RS_USE_RE.finditer(body):
            path = m.group(1).split("::")
            if path[0] == "crate" and len(path) > 1:
                for i in range(len(path) - 1, 0, -1):
                    stem = os.path.join(crate_src, *path[1:i + 1])
                    hit = next((c for c in (stem + ".rs", os.path.join(stem, "mod.rs"))
                                if c in resolver.files), None)
                    if hit:
                        out.append(("file", hit))
                        break
            elif path[0] not in ("self", "super", "std", "core", "alloc", "crate"):
                out.append(("ext", path[0]))
    elif lang == "dart":
        for m in DART_IMPORT_RE.finditer(text):
            spec = m.group(1)
            if spec.startswith("package:"):
                out.append(("ext", spec[8:].split("/")[0]))
            elif not spec.startswith("dart:"):
                cand = os.path.normpath(os.path.join(os.path.dirname(rel), spec))
                if cand in resolver.files:
                    out.append(("file", cand))
    elif lang == "swift":
        for m in SWIFT_IMPORT_RE.finditer(text):
            if m.group(1) not in ("Foundation", "UIKit", "SwiftUI", "Combine", "XCTest"):
                out.append(("ext", m.group(1)))
    return out


