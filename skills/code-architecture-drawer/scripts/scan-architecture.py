#!/usr/bin/env python3
"""Reverse-engineer a codebase's structure: components, dependencies, and gap signals.

Drawing an architecture by reading every file does not scale: the context window runs out
first. This script does the mechanical pass. It builds the import graph and groups files into
components. It measures coupling and stability, and finds entry points, external systems, and
deployment config. Then it emits gap *signals* against the standards in references/.

Every signal is a candidate, not a verdict. The agent must open the evidence and confirm it
before it reaches the report. Gap IDs match references/GAP_CATALOGUE.md.

Usage:
    scan-architecture.py [root] [--depth N] [--include-tests] [--json]
                         [--mermaid components|containers|all] [--max-nodes N]
    scan-architecture.py --self-test

Exits 0 for any scan result — this reports, it never gates.
--self-test exits non-zero on failure so it can be wired into a test suite.
"""

