def manifest_deps(root, files):
    """Declared dependencies per manifest, as {name: manifest path}."""
    deps = {}

    def add(name, where):
        name = name.strip().strip("\"'").lower()
        if name and not name.startswith(("#", "-")):
            deps.setdefault(name, where)

    for f in files:
        base = os.path.basename(f)
        if skipped(f):
            continue
        if base == "package.json":
            data = loose_json(read(root, f)) or {}
            for sect in ("dependencies", "devDependencies", "peerDependencies",
                         "optionalDependencies"):
                for n in (data.get(sect) or {}):
                    add(n, f)
        elif base == "composer.json":
            data = loose_json(read(root, f)) or {}
            for sect in ("require", "require-dev"):
                for n in (data.get(sect) or {}):
                    add(n, f)
        elif base in ("requirements.txt", "requirements-dev.txt", "requirements.in") or \
                re.match(r"requirements.*\.txt$", base):
            for ln in (read(root, f) or "").splitlines():
                m = re.match(r"\s*([A-Za-z0-9_.\-\[\]]+)", ln)
                if m and not ln.strip().startswith(("#", "-")):
                    add(re.sub(r"\[.*\]", "", m.group(1)), f)
        elif base == "pyproject.toml":
            text = read(root, f) or ""
            for m in re.finditer(r"^\s*['\"]([A-Za-z0-9_.\-]+)(?:\[[^\]]*\])?\s*[<>=!~;'\"]",
                                 text, re.M):
                add(m.group(1), f)
            for m in re.finditer(r"^([A-Za-z0-9_.\-]+)\s*=\s*[\"{]", text, re.M):
                if m.group(1).lower() not in ("name", "version", "description", "python",
                                              "readme", "license", "requires-python"):
                    add(m.group(1), f)
        elif base == "go.mod":
            for m in re.finditer(r"^\s*(?:require\s+)?([\w.\-]+\.[\w.\-]+/[\w.\-/]+)\s+v",
                                 read(root, f) or "", re.M):
                add(m.group(1), f)
        elif base == "Gemfile":
            for m in re.finditer(r"^\s*gem\s+['\"]([\w\-]+)", read(root, f) or "", re.M):
                add(m.group(1), f)
        elif base == "Cargo.toml":
            text = read(root, f) or ""
            for sect in re.finditer(r"^\[(?:dev-|build-)?dependencies\]\s*$(.*?)(?=^\[|\Z)",
                                    text, re.M | re.S):
                for m in re.finditer(r"^([\w\-]+)\s*=", sect.group(1), re.M):
                    add(m.group(1), f)
        elif base in ("pom.xml",):
            for m in re.finditer(r"<artifactId>([^<]+)</artifactId>", read(root, f) or ""):
                add(m.group(1), f)
        elif base.endswith((".gradle", ".gradle.kts")):
            for m in re.finditer(r"['\"]([\w.\-]+):([\w.\-]+):", read(root, f) or ""):
                add(m.group(1) + "." + m.group(2), f)
                add(m.group(2), f)
        elif base.endswith(".csproj"):
            for m in re.finditer(r"PackageReference\s+Include=\"([^\"]+)\"", read(root, f) or ""):
                add(m.group(1), f)
        elif base == "pubspec.yaml":
            text = read(root, f) or ""
            for sect in re.finditer(r"^(?:dev_)?dependencies:\s*$(.*?)(?=^\S|\Z)", text,
                                    re.M | re.S):
                for m in re.finditer(r"^  ([\w\-]+):", sect.group(1), re.M):
                    add(m.group(1), f)
        elif base == "mix.exs":
            for m in re.finditer(r"\{:(\w+),", read(root, f) or ""):
                add(m.group(1), f)
    return deps


