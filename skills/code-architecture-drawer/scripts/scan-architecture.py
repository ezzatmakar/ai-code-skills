def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("root", nargs="?", default=".", help="repository root (default: .)")
    ap.add_argument("--depth", type=int, default=None,
                    help="path segments per component (default: auto)")
    ap.add_argument("--scope", metavar="PATH",
                    help="draw components inside one container (e.g. apps/api); imports "
                         "leaving it collapse to one node per target")
    ap.add_argument("--include-tests", action="store_true",
                    help="keep test files in the dependency graph")
    ap.add_argument("--json", action="store_true", help="emit the full scan as JSON")
    ap.add_argument("--mermaid", choices=("components", "containers", "all"),
                    help="emit Mermaid diagram source instead of the summary")
    ap.add_argument("--max-nodes", type=int, default=DEFAULT_MAX_NODES,
                    help="component nodes drawn before the rest collapse (default %d)"
                         % DEFAULT_MAX_NODES)
    ap.add_argument("--max-edges", type=int, default=60,
                    help="edges drawn before the lightest are hidden (default 60); "
                         "cycle edges are always drawn")
    ap.add_argument("--self-test", action="store_true", help="run the built-in fixture")
    args = ap.parse_args(argv)

    if args.self_test:
        return self_test()

    root = os.path.abspath(args.root)
    try:
        top = subprocess.run(["git", "-C", root, "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, timeout=30)
        if top.returncode == 0 and top.stdout.strip() and args.root == ".":
            root = top.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass

    res = scan(root, args.depth, args.include_tests, args.scope)
    if args.json:
        print(json.dumps(res, indent=2, default=list))
    elif args.mermaid:
        if args.mermaid in ("components", "all"):
            print("```mermaid\n%s\n```" % mermaid_components(res, args.max_nodes,
                                                              args.max_edges))
        if args.mermaid in ("containers", "all"):
            print("```mermaid\n%s\n```" % mermaid_containers(res))
    else:
        print(render(res))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        sys.exit(130)
