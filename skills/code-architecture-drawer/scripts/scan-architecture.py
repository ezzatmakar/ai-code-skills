def scoped(rel, scope):
    return rel[len(scope) + 1:] if scope and rel.startswith(scope + "/") else rel


def component_key(rel, depth, split_dirs=None):
    """Group a file into a component: its first `depth` directory segments.

    A monorepo group (packages/foo) counts as one segment and a source root (src/) is free.
    A loose file above the component level, such as `src/index.ts` beside `src/features/`,
    becomes its own node. That way a composition root and a types module never merge into one
    component and fake a cycle.
    """
    parts = rel.split("/")[:-1]
    if not parts:
        return "(root)"
    key, counted, i = [], 0, 0
    while i < len(parts) and counted < depth:
        seg = parts[i]
        if seg in GROUP_ROOTS and i + 1 < len(parts):
            key.append(seg + "/" + parts[i + 1])
            i += 2
        else:
            key.append(seg)
            i += 1
        if seg not in SOURCE_ROOTS:
            counted += 1
    if counted < depth and (split_dirs is None or os.path.dirname(rel) in split_dirs):
        key.append(os.path.splitext(rel.split("/")[-1])[0])
    return "/".join(key)


def mixed_dirs(files):
    """Directories that hold source files *and* subdirectories with source files."""
    dirs = {os.path.dirname(f) for f in files}
    parents = {os.path.dirname(d) for d in dirs if d}
    return dirs & parents


def choose_depth(sources):
    best = 1
    split = mixed_dirs(sources)
    for d in range(1, 6):
        n = len({component_key(f, d, split) for f in sources})
        if n > 40:
            break
        best = d
        if n >= 8:
            break
    return best


