def list_files(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-z", "--cached", "--others",
                              "--exclude-standard"], capture_output=True, text=True, timeout=60)
        if out.returncode == 0:
            return [f for f in out.stdout.split("\0") if f]
    except (OSError, subprocess.SubprocessError):
        pass
    files = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")
                       or d in (".github",)]
        for f in filenames:
            files.append(os.path.relpath(os.path.join(dirpath, f), root))
    return files


def tracked_files(root):
    try:
        out = subprocess.run(["git", "-C", root, "ls-files", "-z"], capture_output=True,
                             text=True, timeout=60)
        if out.returncode == 0:
            return {f for f in out.stdout.split("\0") if f}
    except (OSError, subprocess.SubprocessError):
        pass
    return None


def skipped(rel):
    parts = rel.split("/")
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return True
    return bool(SKIP_FILE_RE.search(parts[-1]))


def read(root, rel, limit=MAX_FILE_BYTES):
    path = os.path.join(root, rel)
    try:
        if os.path.getsize(path) > limit:
            return None
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def is_vendored(text):
    """A licence banner, generator marker, or minified line means someone else's code."""
    head = text[:600]
    if VENDORED_HEAD_RE.search(head):
        return True
    return any(len(ln) > 1000 for ln in text.split("\n", 50)[:50])


def loose_json(text):
    """Parse JSON that may carry comments and trailing commas (tsconfig, jsconfig)."""
    if text is None:
        return None
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j == -1 else j
            continue
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j == -1 else j + 2
            continue
        else:
            out.append(c)
        i += 1
    cleaned = re.sub(r",(\s*[}\]])", r"\1", "".join(out))
    try:
        return json.loads(cleaned)
    except ValueError:
        return None


